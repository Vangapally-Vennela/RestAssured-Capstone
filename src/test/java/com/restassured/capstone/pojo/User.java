package com.restassured.capstone.pojo;

import com.fasterxml.jackson.annotation.JsonInclude;
import com.fasterxml.jackson.annotation.JsonIgnoreProperties;

/**
 * User POJO (Bonus Assignment - "POJO class for User creation").
 *
 * <p>A POJO (Plain Old Java Object) represents a JSON body as a Java class.
 * Rest Assured + Jackson automatically convert it to JSON when passed to
 * {@code .body(user)}, so we never have to hand-write JSON strings.</p>
 *
 * Example JSON produced:
 * <pre>
 * { "name": "QA User", "email": "qa@example.com", "gender": "male", "status": "active" }
 * </pre>
 */
@JsonInclude(JsonInclude.Include.NON_NULL)      // fields that are null are left out of the JSON
@JsonIgnoreProperties(ignoreUnknown = true)     // ignore extra fields returned by the server
public class User {

    private Integer id;       // generated by the server (null when we create a user)
    private String name;
    private String email;     // must be unique on GoRest
    private String gender;    // "male" or "female"
    private String status;    // "active" or "inactive"

    /** Empty constructor required by Jackson. */
    public User() {
    }

    /** Convenience constructor used when building request bodies. */
    public User(String name, String email, String gender, String status) {
        this.name = name;
        this.email = email;
        this.gender = gender;
        this.status = status;
    }

    public Integer getId() { return id; }
    public void setId(Integer id) { this.id = id; }

    public String getName() { return name; }
    public void setName(String name) { this.name = name; }

    public String getEmail() { return email; }
    public void setEmail(String email) { this.email = email; }

    public String getGender() { return gender; }
    public void setGender(String gender) { this.gender = gender; }

    public String getStatus() { return status; }
    public void setStatus(String status) { this.status = status; }
}
